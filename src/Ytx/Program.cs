using YoutubeExplode.Videos.ClosedCaptions;

record Input(string url);

record Options(
    string? Url,
    string Language,
    bool MetadataOnly,
    bool Compact,
    bool ShowHelp,
    bool ShowVersion);

// Property order is the JSON field order. Nullable fields are written as null, never
// omitted, so every document has the same keys.
class Output
{
    public string url { get; set; } = "";
    public string videoId { get; set; } = "";
    public string title { get; set; } = "";
    public string channel { get; set; } = "";
    public string channelId { get; set; } = "";
    public string? uploadDate { get; set; }
    public int? durationSeconds { get; set; }
    public long? viewCount { get; set; }
    public IReadOnlyList<string> keywords { get; set; } = [];
    public string description { get; set; } = "";
    public string captionStatus { get; set; } = CaptionStatus.Skipped;
    public string? captionLanguage { get; set; }
    public string? captionLanguageName { get; set; }
    public bool? captionIsAutoGenerated { get; set; }
    public string? captionError { get; set; }
    public string transcriptRaw { get; set; } = "";
    public string transcript { get; set; } = "";
}

static class CaptionStatus
{
    public const string Ok = "ok";
    public const string None = "none";
    public const string Skipped = "skipped";
    public const string Blocked = "blocked";
    public const string Error = "error";
}

// Source-generated metadata skips reflection setup at startup and keeps JSON
// working under trimming and NativeAOT, where reflection-based serialization is disabled.
[JsonSerializable(typeof(Input))]
[JsonSerializable(typeof(Output))]
partial class YtxJsonContext : JsonSerializerContext
{
}

static partial class Program
{
    private const string Usage = """
        ytx extracts YouTube video metadata and captions as JSON.

        Usage:
          ytx [options] <URL_OR_VIDEO_ID>
          echo '{"url":"URL_OR_VIDEO_ID"}' | ytx [options]

        Arguments:
          URL_OR_VIDEO_ID           A YouTube URL or video ID.

        Options:
          -u, --url <value>         Specify the YouTube URL or video ID explicitly.
          -l, --language <value>    Prefer captions matching a language name or code
                                    (default: English). Falls back to English, then
                                    any track, with a warning on stderr.
              --metadata-only       Skip caption retrieval and return metadata only.
          -c, --compact             Write compact JSON instead of indented JSON.
          -h, -?, --help            Show help and exit.
          -v, --version             Show version and exit.

        Output:
          JSON is written to stdout. Diagnostics are written to stderr.

        Exit codes:
          0  Success, including videos with no captions
          1  Video retrieval or another runtime error
          2  Invalid command-line usage or input
          3  Metadata written, but captions were blocked or failed
        """;

    static async Task<int> Main(string[] args)
    {
        var (options, error) = ParseOptions(args);
        if (error != null)
        {
            Console.Error.WriteLine($"Error: {error}");
            Console.Error.WriteLine("Try 'ytx --help' for more information.");
            return 2;
        }

        if (options!.ShowHelp)
        {
            Console.WriteLine(Usage);
            return 0;
        }

        if (options.ShowVersion)
        {
            Console.WriteLine($"ytx {GetVersion()}");
            return 0;
        }

        string? url = options.Url;
        if (url == null && Console.IsInputRedirected)
        {
            var stdin = await Console.In.ReadToEndAsync();
            if (!string.IsNullOrWhiteSpace(stdin))
            {
                try
                {
                    var input = JsonSerializer.Deserialize(stdin.Trim(),
                        new YtxJsonContext(new JsonSerializerOptions { PropertyNameCaseInsensitive = true }).Input);
                    url = input?.url;
                }
                catch (JsonException ex)
                {
                    Console.Error.WriteLine($"Error: Invalid JSON input: {ex.Message}");
                    return 2;
                }
            }
        }

        if (string.IsNullOrWhiteSpace(url))
        {
            Console.Error.WriteLine("Error: A YouTube URL or video ID is required.");
            Console.Error.WriteLine("Try 'ytx --help' for more information.");
            return 2;
        }

        var videoId = VideoId.TryParse(url);
        if (videoId == null)
        {
            Console.Error.WriteLine($"Error: '{url}' is not a valid YouTube URL or video ID.");
            return 2;
        }

        try
        {
            var client = new YoutubeClient();
            var video = await client.Videos.GetAsync(videoId.Value);
            var output = CreateOutput(video);

            if (!options.MetadataOnly)
            {
                await AddCaptionsAsync(client, video.Id, options.Language, output);
            }

            Console.OutputEncoding = Encoding.UTF8;
            using (var stdout = Console.OpenStandardOutput())
            {
                WriteOutput(stdout, output, options.Compact);
            }

            if (output.captionError != null)
            {
                Console.Error.WriteLine($"Warning: Captions {output.captionStatus}: {output.captionError}");
                return 3;
            }
            return 0;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
            return 1;
        }
    }

    internal static Output CreateOutput(Video video) => new()
    {
        url = $"https://www.youtube.com/watch?v={video.Id}",
        videoId = video.Id.Value,
        title = video.Title ?? "",
        channel = video.Author.ChannelTitle,
        channelId = video.Author.ChannelId.Value,
        uploadDate = video.UploadDate.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
        durationSeconds = video.Duration is { } d ? (int)d.TotalSeconds : null,
        viewCount = video.Engagement.ViewCount,
        keywords = video.Keywords,
        description = video.Description ?? "",
    };

    private static async Task AddCaptionsAsync(YoutubeClient client, VideoId videoId, string language, Output output)
    {
        try
        {
            var manifest = await client.Videos.ClosedCaptions.GetManifestAsync(videoId);
            var track = SelectTrack(manifest.Tracks, language);
            if (track == null)
            {
                output.captionStatus = CaptionStatus.None;
                return;
            }

            if (!LanguageMatches(track.Language.Code, track.Language.Name, language))
            {
                Console.Error.WriteLine(
                    $"Warning: No captions match '{language}'; using {track.Language.Name} ({track.Language.Code}).");
            }

            var captions = await client.Videos.ClosedCaptions.GetAsync(track);
            (output.transcriptRaw, output.transcript) = BuildTranscript(videoId.Value, captions.Captions);
            output.captionStatus = CaptionStatus.Ok;
            output.captionLanguage = track.Language.Code;
            output.captionLanguageName = track.Language.Name;
            output.captionIsAutoGenerated = track.IsAutoGenerated;
        }
        // Only failures of the caption fetch itself are reported in the output. Anything
        // else is a bug and should fail loudly instead of looking like a video without captions.
        catch (Exception ex) when (ex is YoutubeExplodeException or HttpRequestException or TaskCanceledException)
        {
            output.captionStatus = ClassifyCaptionError(ex);
            output.captionError = ex.Message;
        }
    }

    // YouTube blocks by rate limiting, by refusing the request, or by asking the client to
    // prove it is not a bot. Callers can retry later or through another network.
    internal static string ClassifyCaptionError(Exception ex) => ex switch
    {
        RequestLimitExceededException => CaptionStatus.Blocked,
        HttpRequestException { StatusCode: System.Net.HttpStatusCode.Forbidden or System.Net.HttpStatusCode.TooManyRequests }
            => CaptionStatus.Blocked,
        _ when ex.Message.Contains("not a bot", StringComparison.OrdinalIgnoreCase) => CaptionStatus.Blocked,
        _ => CaptionStatus.Error,
    };

    internal static (string Raw, string Markdown) BuildTranscript(string videoId, IEnumerable<ClosedCaption> captions)
    {
        var rawSb = new StringBuilder();
        var mdSb = new StringBuilder();

        foreach (var caption in captions)
        {
            var text = NormalizeCaption(caption.Text);
            if (string.IsNullOrWhiteSpace(text)) continue;

            if (rawSb.Length > 0)
            {
                rawSb.Append(' ');
                mdSb.Append(Environment.NewLine);
            }
            rawSb.Append(text);

            // Appending interpolated strings to a StringBuilder formats in place, with no temporary strings.
            mdSb.Append("- [");
            AppendTimestamp(mdSb, caption.Offset);
            mdSb.Append($"](https://www.youtube.com/watch?v={videoId}&t={(int)caption.Offset.TotalSeconds}s) ");
            mdSb.Append(text);
        }

        return (rawSb.ToString().Trim(), mdSb.ToString().TrimEnd());
    }

    // Writes UTF-8 without a BOM and ends with the platform newline, matching Console.WriteLine.
    internal static void WriteOutput(Stream stream, Output output, bool compact)
    {
        var context = new YtxJsonContext(new JsonSerializerOptions
        {
            WriteIndented = !compact,
            Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
        });

        // Serializing to a string sizes its buffer for the worst-case escape of the whole
        // transcript and then copies it as UTF-16. Writing UTF-8 to the stream avoids both.
        JsonSerializer.Serialize(stream, output, context.Output);
        stream.Write(Encoding.UTF8.GetBytes(Environment.NewLine));
        stream.Flush();
    }

    internal static (Options? Options, string? Error) ParseOptions(string[] args)
    {
        string? url = null;
        var language = "English";
        var metadataOnly = false;
        var compact = false;
        var showHelp = false;
        var showVersion = false;
        var positionalOnly = false;

        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            if (!positionalOnly && arg == "--")
            {
                positionalOnly = true;
            }
            else if (!positionalOnly && arg is "-h" or "-?" or "--help")
            {
                showHelp = true;
            }
            else if (!positionalOnly && arg is "-v" or "--version")
            {
                showVersion = true;
            }
            else if (!positionalOnly && arg is "-c" or "--compact")
            {
                compact = true;
            }
            else if (!positionalOnly && arg == "--metadata-only")
            {
                metadataOnly = true;
            }
            else if (!positionalOnly && arg is "-u" or "--url")
            {
                if (++i >= args.Length) return (null, $"Option '{arg}' requires a value.");
                if (url != null) return (null, "The YouTube URL or video ID can only be specified once.");
                url = args[i];
            }
            else if (!positionalOnly && arg is "-l" or "--language")
            {
                if (++i >= args.Length || string.IsNullOrWhiteSpace(args[i]))
                    return (null, $"Option '{arg}' requires a value.");
                language = args[i];
            }
            else if (!positionalOnly && arg.StartsWith('-'))
            {
                return (null, $"Unknown option '{arg}'.");
            }
            else if (url == null)
            {
                url = arg;
            }
            else
            {
                return (null, "Only one YouTube URL or video ID can be specified.");
            }
        }

        if (showHelp && showVersion)
            return (null, "Options '--help' and '--version' cannot be used together.");

        return (new Options(url, language, metadataOnly, compact, showHelp, showVersion), null);
    }

    internal static string GetVersion()
    {
        var informationalVersion = typeof(Program).Assembly
            .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
        return informationalVersion?.Split('+')[0]
            ?? typeof(Program).Assembly.GetName().Version?.ToString(3)
            ?? "unknown";
    }

    // Best language match first, then human-written over auto-generated. With no match,
    // English is still preferred so an unknown -l keeps the pre-1.0.9 fallback.
    internal static ClosedCaptionTrackInfo? SelectTrack(IEnumerable<ClosedCaptionTrackInfo> tracks, string preference) =>
        tracks
            .OrderByDescending(t => LanguageMatchRank(t.Language.Code, t.Language.Name, preference))
            .ThenByDescending(t => LanguageMatchRank(t.Language.Code, t.Language.Name, "en"))
            .ThenBy(t => t.IsAutoGenerated)
            .FirstOrDefault();

    internal static bool LanguageMatches(string code, string name, string preference) =>
        LanguageMatchRank(code, name, preference) > 0;

    // 4 exact code, 3 exact name, 2 code prefix ("en" matches "en-GB"), 1 name substring, 0 none.
    // Substring needs more than 3 characters: "fr" is inside "Afrikaans" and "en" inside "French".
    internal static int LanguageMatchRank(string code, string name, string preference)
    {
        if (code.Equals(preference, StringComparison.OrdinalIgnoreCase)) return 4;
        if (name.Equals(preference, StringComparison.OrdinalIgnoreCase)) return 3;
        if (code.Length > preference.Length && code[preference.Length] == '-'
            && code.StartsWith(preference, StringComparison.OrdinalIgnoreCase)) return 2;
        if (preference.Length > 3 && name.Contains(preference, StringComparison.OrdinalIgnoreCase)) return 1;
        return 0;
    }

    internal static string ToHhMmSs(TimeSpan ts) => AppendTimestamp(new StringBuilder(), ts).ToString();

    private static StringBuilder AppendTimestamp(StringBuilder sb, TimeSpan ts)
    {
        int h = (int)ts.TotalHours;
        return h > 0
            ? sb.Append($"{h:00}:{ts.Minutes:00}:{ts.Seconds:00}")
            : sb.Append($"{ts.Minutes:00}:{ts.Seconds:00}");
    }

    [GeneratedRegex(@"\s+")]
    private static partial Regex WhitespaceRun();

    internal static string NormalizeCaption(string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return "";
        // \s+ also matches every single space, so the regex would allocate a new string
        // for nearly every caption. Only run it when the text is not already normalized.
        if (NeedsWhitespaceNormalizing(text)) text = WhitespaceRun().Replace(text, " ").Trim();
        return text.Contains("&nbsp;") ? text.Replace("&nbsp;", " ") : text;
    }

    // True when the text has leading or trailing whitespace, a run of spaces, or any
    // whitespace other than a plain space. char.IsWhiteSpace and the regex \s match the same set.
    private static bool NeedsWhitespaceNormalizing(ReadOnlySpan<char> text)
    {
        if (char.IsWhiteSpace(text[0]) || char.IsWhiteSpace(text[^1])) return true;
        for (var i = 1; i < text.Length; i++)
        {
            var c = text[i];
            if (c == ' ' ? text[i - 1] == ' ' : char.IsWhiteSpace(c)) return true;
        }
        return false;
    }
