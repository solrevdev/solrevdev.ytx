using System.Diagnostics;
using YoutubeExplode;
using YoutubeExplode.Videos;

namespace Ytx.Benchmarks;

/// <summary>
/// Fetches a video's metadata and caption track once and saves it as a dataset under data/captured/.
/// That folder is gitignored: captions are third-party content and must not be committed.
/// It also prints how long each network phase took and how much it allocated.
/// </summary>
public static class Capture
{
    public static async Task<int> RunAsync(string dataDir, IReadOnlyList<string> inputs, string language)
    {
        var outDir = Path.Combine(dataDir, "captured");
        Directory.CreateDirectory(outDir);
        var client = new YoutubeClient();
        int failures = 0;

        foreach (var input in inputs)
        {
            var id = VideoId.TryParse(input);
            if (id == null)
            {
                Console.Error.WriteLine($"skip '{input}': not a YouTube URL or video ID");
                failures++;
                continue;
            }

            try
            {
                var sw = Stopwatch.StartNew();
                long a0 = GC.GetTotalAllocatedBytes(true);
                var video = await client.Videos.GetAsync(id.Value);
                var t1 = sw.Elapsed;
                long a1 = GC.GetTotalAllocatedBytes(true);

                var manifest = await client.Videos.ClosedCaptions.GetManifestAsync(video.Id);
                var t2 = sw.Elapsed;
                long a2 = GC.GetTotalAllocatedBytes(true);

                // Same ordering as ytx v1.0.7, so the benchmark formats the track ytx would have chosen.
                // (Issue #3 bug 1: this prefers auto-generated tracks. Fix it here when ytx fixes it.)
                var track = manifest.Tracks
                    .OrderByDescending(t => LanguageMatches(t.Language.Code, t.Language.Name, language))
                    .ThenByDescending(t => t.IsAutoGenerated)
                    .FirstOrDefault();
                if (track == null)
                {
                    Console.Error.WriteLine($"skip {id}: no caption tracks");
                    failures++;
                    continue;
                }

                var captions = await client.Videos.ClosedCaptions.GetAsync(track);
                var t3 = sw.Elapsed;
                long a3 = GC.GetTotalAllocatedBytes(true);

                var d = new Dataset(
                    video.Id.Value, input, video.Title ?? "", video.Description ?? "",
                    captions.Captions.Select(c => new Cap(c.Text, c.Offset, c.Duration)).ToArray());
                var path = Path.Combine(outDir, video.Id.Value + ".json");
                d.Save(path);

                Console.Error.WriteLine(
                    $"{id}: video {t1.TotalMilliseconds:F0} ms / {(a1 - a0) / 1048576.0:F1} MB, " +
                    $"manifest {(t2 - t1).TotalMilliseconds:F0} ms / {(a2 - a1) / 1048576.0:F1} MB, " +
                    $"captions {(t3 - t2).TotalMilliseconds:F0} ms / {(a3 - a2) / 1048576.0:F1} MB, " +
                    $"track '{track.Language.Name}' auto={track.IsAutoGenerated} cues={d.Captions.Length}");
                Console.WriteLine(path);
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"failed {id}: {ex.Message}");
                failures++;
            }
        }

        return failures == 0 ? 0 : 1;
    }

    // Copy of Program.LanguageMatches in ytx v1.0.7.
    static bool LanguageMatches(string code, string name, string preference) =>
        code.Equals(preference, StringComparison.OrdinalIgnoreCase)
        || name.Equals(preference, StringComparison.OrdinalIgnoreCase)
        || name.Contains(preference, StringComparison.OrdinalIgnoreCase);
}
